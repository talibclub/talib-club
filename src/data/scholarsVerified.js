function mergeVerifiedMaps(...maps) {
  const out = {}
  for (const map of maps) {
    for (const [id, patch] of Object.entries(map || {})) {
      out[id] = out[id] ? { ...out[id], ...patch } : { ...patch }
    }
  }
  return out
}

export const ALL_VERIFIED_SCHOLARS = mergeVerifiedMaps(
  VERIFIED_SCHOLARS,
  VERIFIED_SCHOLARS_MORE,
  VERIFIED_WORKS_CLASSICAL,
  VERIFIED_WORKS_REVIVAL_MODERN
)

export { ADDED_SCHOLARS }

/**
 * รวมข้อมูลอุละมาอ์จาก Firestore เข้ากับข้อมูลที่ตรวจสอบแล้ว
 * เติมรายชื่ออุละมาอ์สำคัญที่ขาดตก และปรับมาตรฐานทับศัพท์ภาษาไทยให้สม่ำเสมอ
 */
function normalizeManhaj(mh) {
  if (mh === "สะลัฟี") return "สะละฟี"
  if (mh === "กลาสสิก") return "คลาสสิก"
  return mh
}

export function mergeScholarsList(rawScholars = []) {
  const result = []
  const existingIds = new Set()
  for (const s of rawScholars) {
    if (!s || s.deleted) continue
    existingIds.add(String(s.id))
    const patch = ALL_VERIFIED_SCHOLARS[s.id]
    if (patch?.duplicateOf) continue
    if (patch) {
      const merged = {
        ...s,
        ...patch,
        id: s.id,
        verified: true,
      }
      merged.name = normalizeScholarThaiName(merged.name)
      if (merged.note) merged.note = normalizeScholarThaiText(merged.note)
      if (merged.bio) merged.bio = normalizeScholarThaiText(merged.bio)
      merged.mh = normalizeManhaj(merged.mh)
      result.push(merged)
    } else {
      result.push({
        ...s,
        name: normalizeScholarThaiName(s.name),
        note: s.note ? normalizeScholarThaiText(s.note) : s.note,
        bio: s.bio ? normalizeScholarThaiText(s.bio) : s.bio,
        mh: normalizeManhaj(s.mh),
      })
    }
  }
  for (const added of ADDED_SCHOLARS) {
    if (!existingIds.has(String(added.id))) {
      result.push({
        ...added,
        name: normalizeScholarThaiName(added.name),
        note: added.note ? normalizeScholarThaiText(added.note) : added.note,
        bio: added.bio ? normalizeScholarThaiText(added.bio) : added.bio,
        mh: normalizeManhaj(added.mh),
        verified: true,
      })
    }
  }
  return result
}
